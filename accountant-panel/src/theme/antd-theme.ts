import { theme, type ThemeConfig } from "antd";

/** CSS is the single palette source, including nested styleguide previews. */
export function getAntdTheme(
  dark: boolean,
  reducedMotion = false,
  element: Element = document.documentElement,
): ThemeConfig {
  const styles = getComputedStyle(element);
  const value = (name: string) => styles.getPropertyValue(`--${name}`).trim();
  const number = (name: string) => parseFloat(value(name));
  const duration = (name: string) => `${number(name) / 1000}s`;
  return {
    algorithm: dark ? theme.darkAlgorithm : theme.defaultAlgorithm,
    token: {
      colorPrimary: value("brand-primary"),
      colorPrimaryHover: value("brand-primary-hover"),
      colorPrimaryActive: value("brand-primary-pressed"),
      colorPrimaryBg: value("brand-bg"),
      colorPrimaryBgHover: value("brand-bg"),
      colorPrimaryText: value("text-primary"),
      colorSuccess: value("income-fg"),
      colorSuccessBg: value("income-bg"),
      colorError: value("expense-fg"),
      colorErrorBg: value("expense-bg"),
      colorWarning: value("warning-fg"),
      colorWarningBg: value("warning-bg"),
      colorInfo: value("info-fg"),
      colorInfoBg: value("info-bg"),
      colorLink: value("info-fg"),
      colorLinkHover: value("info-fg"),
      colorLinkActive: value("info-fg"),
      colorTextBase: value("text-primary"),
      colorText: value("text-primary"),
      colorTextHeading: value("text-primary"),
      colorTextSecondary: value("text-secondary"),
      colorTextDescription: value("text-helper"),
      colorTextPlaceholder: value("text-helper"),
      colorBgBase: value("bg-app"),
      colorBgLayout: value("bg-app"),
      colorBgContainer: value("bg-surface"),
      colorBgElevated: value("bg-surface-raised"),
      colorFillAlter: value("bg-subtle"),
      colorBorder: value("border-strong"),
      colorBorderSecondary: value("border"),
      borderRadius: number("radius-control"),
      borderRadiusLG: number("radius-card"),
      borderRadiusSM: number("radius-control"),
      fontFamily: value("font-ui"),
      fontFamilyCode: value("font-numeric"),
      fontSize: number("font-body"),
      fontSizeSM: number("font-caption"),
      fontWeightStrong: number("weight-heading"),
      controlHeight: number("control-height"),
      controlHeightSM: number("control-compact"),
      controlHeightLG: number("control-large"),
      padding: number("space-4"),
      paddingSM: number("space-3"),
      paddingLG: number("space-6"),
      margin: number("space-4"),
      boxShadow: value("shadow-popover"),
      boxShadowSecondary: value("shadow-modal"),
      motion: !reducedMotion,
      motionDurationFast: duration("motion-micro"),
      motionDurationMid: duration("motion-standard"),
      motionDurationSlow: duration("motion-large"),
      motionEaseInOut: value("ease-standard"),
      motionEaseOut: value("ease-enter"),
      motionEaseInBack: value("ease-exit"),
    },
    components: {
      Button: {
        primaryColor: value("brand-on-primary"),
        primaryShadow: "none",
        defaultShadow: "none",
        dangerShadow: "none",
        defaultBg: value("bg-surface"),
        defaultBorderColor: value("border-strong"),
        defaultColor: value("text-primary"),
        defaultHoverColor: value("text-primary"),
        defaultHoverBorderColor: value("brand-primary"),
        defaultHoverBg: value("bg-subtle"),
        defaultActiveColor: value("text-primary"),
        defaultActiveBorderColor: value("brand-primary-pressed"),
      },
      Tabs: {
        titleFontSize: number("font-table"),
        itemColor: value("text-secondary"),
        itemSelectedColor: value("text-primary"),
        itemHoverColor: value("text-primary"),
        inkBarColor: value("brand-primary"),
      },
      Descriptions: { labelColor: value("text-secondary") },
      Table: {
        headerBg: value("bg-subtle"),
        rowHoverBg: value("bg-subtle"),
        rowSelectedBg: value("brand-bg"),
        cellPaddingBlock: number("space-3"),
      },
      Input: {
        activeBorderColor: value("brand-primary"),
        hoverBorderColor: value("border-strong"),
        activeShadow: "none",
      },
      InputNumber: {
        activeBorderColor: value("brand-primary"),
        activeShadow: "none",
      },
      Select: {
        optionSelectedBg: value("brand-bg"),
        optionSelectedColor: value("text-primary"),
      },
      Checkbox: {
        colorPrimary: value("brand-primary"),
        colorWhite: value("brand-on-primary"),
      },
      Modal: { borderRadiusLG: number("radius-modal") },
      Pagination: {
        itemActiveBg: value("brand-bg"),
        colorPrimary: value("text-primary"),
        colorPrimaryHover: value("text-primary"),
      },
      Progress: {
        defaultColor: value("brand-primary"),
        remainingColor: value("bg-subtle"),
      },
      Skeleton: {
        gradientFromColor: value("bg-subtle"),
        gradientToColor: value("border"),
      },
    },
  };
}
